import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { CongressClient } from "./congress/client.mjs";
import { dedupeById, normalizeLegislation } from "./congress/normalizers.mjs";

const root = resolve(import.meta.dirname, "..");
const rawPath = resolve(root, "data/raw/congress-latest.json");
const generatedPath = resolve(root, "src/data/generated/congress.ts");
const supportedMembers = [
  { id: "jamie-raskin", bioguideId: "R000606", chamber: "house" },
  { id: "chris-van-hollen", bioguideId: "V000128", chamber: "senate" },
  { id: "angela-alsobrooks", bioguideId: "A000386", chamber: "senate" },
  { id: "nancy-pelosi", bioguideId: "P000197", chamber: "house" },
  { id: "alex-padilla", bioguideId: "P000145", chamber: "senate" },
  { id: "adam-schiff", bioguideId: "S001150", chamber: "senate" },
];

if (!process.env.CONGRESS_API_KEY) {
  console.error("Congress ingestion failed: CONGRESS_API_KEY is required. Add it to your environment; see .env.example.");
  process.exit(1);
}

const now = new Date().toISOString();
const client = new CongressClient(process.env.CONGRESS_API_KEY);
const raw = { retrievedAt: now, members: [] };
const normalized = [];
const errors = [];

for (const member of supportedMembers) {
  try {
    const [sponsored, cosponsored] = await Promise.all([
      client.getAll(`member/${member.bioguideId}/sponsored-legislation`, "sponsoredLegislation"),
      client.getAll(`member/${member.bioguideId}/cosponsored-legislation`, "cosponsoredLegislation"),
    ]);
    const inCurrentCongress = (bill) => bill.congress === 119;
    const memberRaw = { ...member, sponsored, cosponsored };
    raw.members.push(memberRaw);
    for (const [kind, bills] of [["sponsored", sponsored], ["cosponsored", cosponsored]]) {
      for (const bill of bills.filter(inCurrentCongress)) {
        normalized.push(normalizeLegislation({ memberId: member.id, chamber: member.chamber, kind, bill, retrievedAt: now }));
      }
    }
  } catch (error) {
    errors.push({ memberId: member.id, message: error.message });
  }
}

await mkdir(dirname(rawPath), { recursive: true });
await writeFile(rawPath, `${JSON.stringify(raw, null, 2)}\n`);
const sources = dedupeById(normalized.map((entry) => entry.sourceRecord));
const bills = dedupeById(normalized.map((entry) => entry.bill));
const activities = dedupeById(normalized.map((entry) => entry.activity));
const generated = `// Generated by npm run ingest:congress. Do not edit by hand.\nimport type { ActivityRecord, BillContext, SourceRecord } from \"../../domain/models\";\n\nexport const generatedCongressSourceRecords: SourceRecord[] = ${JSON.stringify(sources, null, 2)};\nexport const generatedCongressBills: BillContext[] = ${JSON.stringify(bills, null, 2)};\nexport const generatedCongressActivity: ActivityRecord[] = ${JSON.stringify(activities, null, 2)};\n`;
await writeFile(generatedPath, generated);

console.log("Congress ingestion complete");
console.log(`Members processed: ${supportedMembers.length}`);
console.log(`Bills fetched: ${bills.length}`);
console.log("Amendments fetched: 0 (not in this bounded member-legislation pass)");
console.log(`Activities generated: ${activities.length}`);
console.log(`Raw source records: ${sources.length}`);
console.log(`Errors: ${errors.length}`);
for (const error of errors) console.error(`- ${error.memberId}: ${error.message}`);
if (errors.length === supportedMembers.length) process.exitCode = 1;
